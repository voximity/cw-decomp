//! Bit-exact port of MSVCR110's SSE2 `pow`: `msvcr110.dll` export `_libm_sse2_pow_precise`
//! (RVA 0x39840), which Server.exe imports (thunk `0x0054ab14`). The game calls it with
//! single-precision arguments widened to double and the result rounded back to float, either
//! inline or through the wrapper at `Server.exe 0x004055a0` (`(float)pow((double)x,
//! (double)y)`); callers include the creature stat formulas (`cube::Creature::armor`
//! 0x00408300, `maxHp` 0x0040fda0, `itemPower` 0x00410f00, ...), `cube::World::applyHit`
//! 0x004cea80, `cube::World::creatureAttack` 0x004cfd50, `cube::World::tick` 0x005322d0 and
//! `cube::World::generateDungeon` 0x00500300.
//!
//! Transcribed from the disassembly (capstone over `game/msvcr110.dll`), one statement per
//! SSE2 instruction in the original order; `_lo` / `_hi` name the lanes of a packed register.
//! Checked against `tests/golden/pow_msvcr110.txt` (`tools/oracle/libm_emu.py`).
//!
//! # Algorithm
//!
//! `x = 2^E m` with `m` in `[1, 2)`. Three table lookups on successive bits give
//! `R = A1 A2 A3 ~ 1/m` (with a `1/ln 2` factor folded in) and `L = B1 + B2 + B3 ~ -log2 R`
//! as a head/tail pair, so `log2 x = E + L + log2(1 + u)` with `u = m R - c`, evaluated with
//! exact product splitting (`m` and `R` cut at 27 bits) to recover the rounding error of
//! `m R`. `log2(1 + u)` is a short polynomial. Then `y log2 x = 128 n'/128 + r` with
//! `n = round(128 y_hi L_hi)`, and `2^(y log2 x) = 2^(n >> 7) * T[n & 127] * 2^r` with a
//! degree-4 polynomial for `2^r - 1`.
//!
//! When `2^(n >> 7)` is not a normal double the result is built in two steps with an
//! intermediate scale and a head cut to the precision the final (possibly subnormal) result
//! has, so that the last multiplication rounds once; no x87 arithmetic is involved (the
//! routine's only x87 code is the fallback for a non-default MXCSR / control word).
//!
//! # Special cases
//!
//! Negative `x` is accepted for integer `y` (sign from the parity of `y`), subnormal `x` is
//! pre-scaled by `2^64`. Otherwise the usual C99 table, with these MSVC particulars (all
//! reproduced from the code and the error handler at RVA 0xc09c8 with the default
//! `_matherr`): `pow(x, NaN)` and `pow(NaN, y)` return the NaN quieted (`x + x` / `y + y`,
//! so also `pow(1, NaN)` is NaN), except `pow(NaN, ±0) = NaN` too (error 29 returns `x`) while
//! `pow(±0, ±0) = 1` (error 26); `pow(-finite, non-integer)` is the default NaN (error 28).

