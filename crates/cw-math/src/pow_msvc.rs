// Constants (RVA 0x3d410..0x3d42f and 0x3dc30..0x3dcef).
const LOG_P1: [f64; 2] = [
    f64::from_bits(0x3fc47fd462b3b816),
    f64::from_bits(0x3e79c3a6966457ee),
]; // (0x3d410)
const LOG_P2: [f64; 2] = [
    f64::from_bits(0xbfb550472a8bb463),
    f64::from_bits(0xbfd62e4346694107),
]; // (0x3d420)
const SHIFTER: f64 = f64::from_bits(0x4338000000000000); //  (0x3dc30)
const FRAC: u64 = 0x000fffffffffffff; //                    (0x3dc40)
const ONE: u64 = 0x3ff0000000000000; //                     (0x3dc50)
const ABS: u64 = 0x7fffffffffffffff; //                     (0x3dc60)
const EXP_P1: [f64; 2] = [
    f64::from_bits(0x3f55d87fe78a6731),
    f64::from_bits(0x3fac6b08d704a0bf),
]; // (0x3dc70)
const EXP_P2: [f64; 2] = [
    f64::from_bits(0x3f83b2ab6fba4e77),
    f64::from_bits(0x3fcebfbdff82c58e),
]; // (0x3dc80)
const LN2: f64 = f64::from_bits(0x3fe62e42fefa39ef); //      (0x3dc90)
const MASK_27: u64 = 0xfffffffff8000000; //                 (0x3dc98)
const NEG_LOG2E_HI: f64 = f64::from_bits(0xbff7154740000000); // (0x3dca0)
const INF: u64 = 0x7ff0000000000000; //                     (0x3dcb0)
const NEG_INF: u64 = 0xfff0000000000000; //                 (0x3dcb8)
const NEG_ZERO: u64 = 0x8000000000000000; //                (0x3dcc0)
const NEG_HUGE: f64 = f64::from_bits(0xffe0000000000000); // -2^1023 (0x3dcc8)
const HUGE: f64 = f64::from_bits(0x7fe0000000000000); //     2^1023 (0x3dcd0)
const TINY: f64 = f64::from_bits(0x0010000000000000); //     2^-1022 (0x3dcd8)
const DEFAULT_NAN: u64 = 0xfff8000000000000; //             (0x3dce0)

#[inline]
fn f(b: u64) -> f64 {
    f64::from_bits(b)
}

#[inline]
fn hw(v: f64) -> u32 {
    (v.to_bits() >> 48) as u32
}

/// `cvtsd2si` under round-to-nearest: out of range or NaN gives `0x80000000`.
fn cvtsd2si(v: f64) -> i32 {
    let r = v.round_ties_even();
    if r >= -2147483648.0 && r < 2147483648.0 {
        r as i32
    } else {
        i32::MIN
    }
}

/// `pow` exactly as `msvcr110.dll!_libm_sse2_pow_precise` (RVA 0x39840) computes it, under
/// the default MXCSR and x87 control word.
pub fn pow(x: f64, y: f64) -> f64 {
    let xb = x.to_bits();
    let x0 = xb >> 44; // xmm0 after `psrlq 0x2c`
    let i1 = ((((x0 as u32) & 0xff) + 1) & 0x1fe) as usize / 2;
    let x7 = f(xb & FRAC | ONE) * f(A1[i1]); // xmm7 = m * A1
    let x5 = f(A1[i1]);
    let x6 = [f(B1[i1][0]), f(B1[i1][1])];
    let ecx = hw(x);
    let edx = 0x7fefu32.wrapping_sub(ecx);
    if (ecx.wrapping_sub(0x10) | edx) >= 0x8000_0000 {
        return special_x(x, y, edx);
    }
    core(x0, x7, x5, x6, xb, 0, 0x3fe7f, x, y)
}

/// RVA 0x398f3: the logarithm and exponential for an `x` whose fraction has been looked up
/// (`x7 = m A1`, `x5 = A1`, `x6 = B1`). `xbits` is the (possibly pre-scaled) `x`, `x0` its
/// top 20 bits (`x >> 44`), `edx` the exponent bias to remove from them, `ecx` the sign of
/// the result in bit 18 (`0x40000`) or 0.
#[allow(clippy::too_many_arguments)]
fn core(
    x0: u64,
    x7: f64,
    x5: f64,
    x6: [f64; 2],
    xbits: u64,
    ecx: u32,
    edx: u32,
    x: f64,
    y: f64,
) -> f64 {
    // psubq, psrlq 8, cvtdq2pd: the exponent E (the low dword, as a signed integer).
    let e = f64::from(((x0.wrapping_sub(u64::from(edx))) >> 8) as u32 as i32);
    let x3 = x7;
    let i2 = (((((x7.to_bits() >> 38) as u32) & 0xff) + 1) & 0x1fe) as usize / 2;
    let x4 = xbits & FRAC;
    let x3 = x3 * f(A2[i2]);
    let x5 = x5 * f(A2[i2]);
    let mut x6 = [x6[0] + f(B2[i2][0]), x6[1] + f(B2[i2][1])];
    let x4 = f(x4 | ONE); // m
    x6[0] += e;
    let x1 = f(MASK_27 & x4.to_bits()); // m_hi
    let x2 = x3;
    let i3 = (((((x3.to_bits() >> 31) as u32) & 0x1ff) + 1) & 0x3fe) as usize / 2;
    let x4 = x4 - x1; // m_lo
    let x7 = NEG_LOG2E_HI;
    let x5 = x5 * f(A3[i3]); // R
    let x2 = x2 * f(A3[i3]); // z = m R
    x6 = [x6[0] + f(B3[i3][0]), x6[1] + f(B3[i3][1])];
    let x0 = f(MASK_27 & x5.to_bits()); // R_hi
    let x5 = x5 - x0; // R_lo
    let x7 = x7 + x2; // u
    let x3 = x0;
    let x0 = x0 * x1; // R_hi m_hi
    let x1 = x1 * x5; // m_hi R_lo
    let x3 = x3 * x4; // R_hi m_lo
    let x2 = x2 - x0;
    let x4 = x4 * x5; // m_lo R_lo
    let x0 = x6[0];
    let x2 = x2 - x1;
    x6[0] += x7; // s = L + E + u
    let ey = hw(y);
    let x2 = x2 - x3;
    let x0 = x0 - x6[0];
    let es = hw(x6[0]);
    let x2 = x2 - x4; // c = z - m R (exact)
    let mut x4 = x6[0];
    let x0 = x0 + x7;
    let u = x7 - x2; // xmm7 = [u', u']
    x6[0] -= x2; // s'
    if ey & 0x7ff0 >= 0x7ff0 {
        return y_inf_nan(x, y);
    }
    let eax = (ey & 0x7ff0).wrapping_sub(0x3ff0).wrapping_add(es & 0x7ff0);
    if (0x40a0u32.wrapping_sub(eax) | eax.wrapping_sub(0x3c70)) >= 0x8000_0000 {
        // RVA 0x3a31d: estimate failed; look at the actual product y * s'.
        let p = hw(y * x6[0]) & 0x7ff0;
        let t = p.wrapping_sub(0x3c70);
        if (0x40a0u32.wrapping_sub(p) | t) >= 0x8000_0000 {
            if t >= 0x8000_0000 {
                // |y log2 x| < 2^-56: +-1.
                return f(u64::from(ecx | 0x1ff80) << 45);
            }
            // RVA 0x3a364: overflow if the signs of y and log2|x| agree.
            let ex = (hw(x) & 0x7ff0).wrapping_sub(0x3ff0);
            return if (ey ^ ex) & 0x8000 == 0 {
                overflow(ecx)
            } else {
                underflow(ecx)
            };
        }
        // Back to the main path; xmm4 now holds the product instead of s.
        x4 = y * x6[0];
    }
    // RVA 0x39a45.
    let x4 = x4 - x6[0];
    let x2 = x2 - x4;
    let x4 = f(MASK_27 & x6[0].to_bits()); // L_hi
    let x3 = f(MASK_27 & y.to_bits()); // y_hi
    let x0 = x0 - x2; // low part of s
    let x5 = x3;
    let x3 = x3 * x4;
    x6[0] -= x4; // L_lo
    let x1 = y - x5; // y_lo
    let x3 = x3 * 128.0;
    let x5 = x5 * x6[0];
    let x4 = x4 * x1;
    let n = cvtsd2si(x3);
    x6[0] *= x1;
    let x5 = x5 + x4;
    let x4 = x6[1]; // table tails
    let x5 = x5 + x6[0];
    let edx = 0x1ff7fu32.wrapping_sub(n as u32);
    let eax = (n as u32).wrapping_add(0x1e1ff);
    if ((edx | eax) as i32) <= 0 {
        return scaled(n, ecx, x0, x3, x4, x5, u, y);
    }
    let ecx = ecx.wrapping_add(n as u32);
    let j = (n & 0x7f) as usize;
    let ecx = (ecx & 0xffff_ff80).wrapping_add(0x1ff80);
    let x4 = x4 + x0;
    let t = x3;
    let k = (x3 + SHIFTER) - SHIFTER;
    let p_lo = LOG_P1[0] * u; // xmm2
    let p_hi = LOG_P1[1] * u;
    let u2 = u * u; // xmm7
    let frac = t - k; // xmm0
    let tj = EXP2[j];
    let q_lo = LOG_P2[0] * u2; // xmm1
    let q_hi = LOG_P2[1] * u2;
    let p_lo = p_lo + q_lo;
    let p_hi = p_hi + q_hi;
    let p = p_lo * u2;
    let p = p + p_hi;
    let p = p + x4;
    let sc = f(u64::from(ecx) << 45);
    let p = p * y;
    let frac = frac * f(0x3f80000000000000); // 2^-7
    let x5 = x5 + p;
    let t_lo = f(tj[0]) * sc; // xmm3 = T[j] * [S, S]
    let t_hi = f(tj[1]) * sc;
    let r = frac + x5;
    exp2_tail(r, t_lo, t_hi)
}

/// The shared `2^r` polynomial (RVA 0x39b71..0x39bb3 / 0x3a1c2..0x3a215 up to the final sums):
/// returns `(r2 T_lo e_lo, e_hi T_lo, ln2 r T_lo)` pieces summed in the original order.
fn exp2_parts(r: f64, t_lo: f64) -> (f64, f64, f64) {
    let q_lo = EXP_P1[0] * r; // xmm6
    let q_hi = EXP_P1[1] * r;
    let l = LN2 * r; // xmm4
    let r2 = r * r; // xmm0 = [r^2, r^2]
    let e_lo = EXP_P2[0] + q_lo; // xmm7
    let e_hi = EXP_P2[1] + q_hi;
    let e_lo = e_lo * r2;
    let e_hi = e_hi * r2;
    let a = r2 * t_lo; // xmm0.lo
    let b = e_hi; // xmm6
    let a = a * e_lo;
    let b = b * t_lo;
    let l = l * t_lo;
    (a, b, l)
}

fn exp2_tail(r: f64, t_lo: f64, t_hi: f64) -> f64 {
    let (a, b, l) = exp2_parts(r, t_lo);
    let v = a + t_hi;
    let v = v + b;
    let v = v + l;
    v + t_lo
}

/// RVA 0x3a0bb: `2^(n >> 7)` outside the normal range.
#[allow(clippy::too_many_arguments)]
fn scaled(n: i32, ecx: u32, x0: f64, x3: f64, x4: f64, x5: f64, u: f64, y: f64) -> f64 {
    let (ecx, edx, edi) = if n > 0 {
        if n >= 0x40000 {
            return overflow(ecx);
        }
        let edx = ((n - 0x80) as u32) & 0xffff_ff80;
        (ecx.wrapping_add(0x3ff00), edx, 0x3ff0u64)
    } else {
        if n <= -0x3fe00 {
            return underflow(ecx);
        }
        let edx = ((n as u32) & 0xffff_ff80).wrapping_add(0x3fe80);
        (ecx.wrapping_add(0x80), edx, 0u64)
    };
    let j = (n & 0x7f) as usize;
    let x4 = x4 + x0;
    let t = x3;
    let k = (x3 + SHIFTER) - SHIFTER;
    let esi = edx.wrapping_sub(0x1ff80) as i32;
    let p_lo = LOG_P1[0] * u;
    let p_hi = LOG_P1[1] * u;
    let u2 = u * u;
    let frac = t - k;
    let tj = EXP2[j];
    let q_lo = LOG_P2[0] * u2;
    let q_hi = LOG_P2[1] * u2;
    let p_lo = p_lo + q_lo;
    let p_hi = p_hi + q_hi;
    let p = p_lo * u2;
    let p = p + p_hi;
    let p = p + x4;
    let sc1 = f(u64::from(edx) << 45);
    let shift = ((esi.wrapping_neg() >> 7) + 2) as u32;
    let shift = shift.wrapping_add(shift & 0x20);
    let p = p * y;
    let frac = frac * f(0x3f80000000000000);
    let x5 = x5 + p;
    let t_lo = f(tj[0]) * sc1;
    let t_hi = f(tj[1]) * sc1;
    let r = frac + x5;
    let (a, b, l) = exp2_parts(r, t_lo);
    let sc2 = f(u64::from(ecx) << 45); // xmm7
    let mask = if shift >= 64 { 0 } else { u64::MAX << shift };
    let v = a + t_hi;
    let v = v + b;
    let h = f(mask & t_lo.to_bits()); // xmm1
    let v = v + l;
    let rem = t_lo - h; // xmm3
    let h2 = f((h + v).to_bits() & mask); // xmm1
    let one = f(edi << 48); // xmm6: 1.0 or 0.0
    let d = h - h2; // xmm2
    let v = v + d;
    let v = v + rem;
    if esi > 0 {
        let v = v + h2;
        let v = v * sc2;
        let w = one * v;
        v + w
    } else {
        let v = v * sc2;
        let h2 = h2 * sc2;
        let v = v + h2;
        let w = one * v;
        v + w
    }
    // Results with an all-ones or zero exponent go through the error handler (24, 25),
    // which returns them unchanged.
}

/// RVA 0x3a2ed: overflow, `±2^1023 * 2^1023` (error 24, returned unchanged).
fn overflow(ecx: u32) -> f64 {
    if ecx == 0 {
        HUGE * HUGE
    } else {
        NEG_HUGE * HUGE
    }
}

/// RVA 0x3a2ca: underflow, `2^-1022 * 2^-1022` with the sign in `ecx` (error 25).
fn underflow(ecx: u32) -> f64 {
    f((TINY * TINY).to_bits() | (u64::from(ecx) << 45))
}

/// Whether `y` (finite, nonzero) is an integer: the test at RVA 0x39c02..0x39c2d.
fn is_integer(y: f64) -> bool {
    let yb = y.to_bits();
    let ey = ((yb & ABS) >> 52) as i32;
    let k = (ey - 0x3f3).max(0) as u32; // psubd + pmaxsw
    let v = yb | NEG_INF; // y | 0xfff0...
    let shifted = if k >= 64 { 0 } else { v << k };
    shifted == 0
}

/// `(y << (ey - 0x3f4))` as `psllq` computes it (the count is a zero-extended dword).
fn parity_bits(y: f64) -> u64 {
    let yb = y.to_bits();
    let ey = ((yb & ABS) >> 52) as u32;
    let k = u64::from(ey.wrapping_sub(0x3f4));
    if k >= 64 { 0 } else { yb << k }
}

/// RVA 0x39bb7: `x` negative, zero, subnormal, infinite or NaN. `edx = 0x7fef - hw(x)`.
fn special_x(x: f64, y: f64, edx: u32) -> f64 {
    let xb = x.to_bits();
    let yb = y.to_bits();
    let ay_hi = ((yb & ABS) >> 32) as u32;
    if ay_hi >= 0x7ff0_0000 {
        // RVA 0x39cbe: y infinite or NaN.
        let ax_hi = ((xb >> 32) as u32) & 0x7fff_ffff;
        let lo = xb as u32;
        if ax_hi > 0x7ff0_0000 || (ax_hi == 0x7ff0_0000 && lo != 0) {
            return f((x + x).to_bits()); // x NaN: error 1006
        }
        return y_inf_nan_tail(x, y);
    }
    if (yb as u32 | ay_hi) == 0 {
        return y_zero(x);
    }
    if (edx as i32) >= 0 {
        // Positive zero or subnormal.
        return subnormal_x(x, y, 0);
    }
    let hwx = hw(x); // neg edx; add edx, 0x7fef
    let int = is_integer(y);
    if hwx & 0x7fff >= 0x7ff0 {
        return x_inf_nan(x, y, int);
    }
    if !int {
        // RVA 0x39ef2: negative non-integer power.
        if xb & ABS == 0 {
            return zero_x(x, y, 0);
        }
        // `SNAN * SNAN` raises invalid; the default NaN is returned (error 28).
        return f(DEFAULT_NAN);
    }
    let odd = parity_bits(y) == NEG_ZERO;
    let ecx = if odd { 0x40000 } else { 0 };
    if hwx & 0x7fff < 0x10 {
        return subnormal_x(x, y, ecx);
    }
    // Negative normal x, integer y: back to the main path with the sign bit in the bias.
    let x0 = xb >> 44;
    let i1 = ((((x0 as u32) & 0xff) + 1) & 0x1fe) as usize / 2;
    let x7 = f(xb & FRAC | ONE) * f(A1[i1]);
    core(
        x0,
        x7,
        f(A1[i1]),
        [f(B1[i1][0]), f(B1[i1][1])],
        xb,
        ecx,
        0xbfe7f,
        x,
        y,
    )
}

/// RVA 0x39cff: `x` zero or subnormal (sign already resolved into `ecx`).
fn subnormal_x(x: f64, y: f64, ecx: u32) -> f64 {
    let xb = x.to_bits();
    let xs = f(0x43f0000000000000) * x; // 2^64 x
    if xb as u32 == 0 && (xb >> 32) as u32 & 0x7fff_ffff == 0 {
        return zero_x(x, y, ecx);
    }
    let sb = xs.to_bits();
    let x0 = (sb & ABS) >> 44;
    let i1 = ((((x0 as u32) & 0xff) + 1) & 0x1fe) as usize / 2;
    let x7 = f(sb & FRAC | ONE) * f(A1[i1]);
    core(
        x0,
        x7,
        f(A1[i1]),
        [f(B1[i1][0]), f(B1[i1][1])],
        sb,
        ecx,
        0x43e7f,
        x,
        y,
    )
}

/// RVA 0x39d92: `x = ±0`, `y` finite nonzero.
fn zero_x(x: f64, y: f64, ecx: u32) -> f64 {
    let hx = (x.to_bits() >> 32) as u32;
    let sign = hx & (ecx << 13);
    if y.to_bits() >> 63 != 0 {
        // Division by zero (error 27): ±inf.
        return f(u64::from(0x7ff0_0000 | sign) << 32);
    }
    if sign != 0 { f(NEG_ZERO) } else { 0.0 }
}

/// RVA 0x3a033: `y = ±0` with a special `x`.
fn y_zero(x: f64) -> f64 {
    let xb = x.to_bits();
    let ax_hi = ((xb >> 32) as u32) & 0x7fff_ffff;
    let lo = xb as u32;
    if (lo | ax_hi) == 0 {
        return f(ONE); // error 26, whose handler stores 1.0
    }
    if ax_hi > 0x7ff0_0000 || (ax_hi == 0x7ff0_0000 && lo != 0) {
        // error 29: the handler returns x through `fld`/`fstp`, quieting it.
        return f(xb | 0x0008_0000_0000_0000);
    }
    f(ONE)
}

/// RVA 0x39de7: `x` infinite or NaN, `y` finite nonzero.
fn x_inf_nan(x: f64, y: f64, int: bool) -> f64 {
    let xb = x.to_bits();
    if xb & FRAC != 0 {
        return x + x; // NaN: error 1006
    }
    let yneg = y.to_bits() >> 63 != 0;
    if xb >> 63 == 0 || !int || parity_bits(y) == 0 {
        // +inf, or -inf to a non-integer or even power.
        return if yneg { 0.0 } else { f(INF) };
    }
    if yneg { f(NEG_ZERO) } else { f(NEG_INF) }
}

/// RVA 0x39f38: `x` positive normal, `y` infinite or NaN.
fn y_inf_nan(x: f64, y: f64) -> f64 {
    let xb = x.to_bits();
    if y.to_bits() & FRAC != 0 {
        return y + y; // error 1006
    }
    if xb as u32 == 0 && (xb >> 32) as u32 == 0x3ff0_0000 {
        return f(ONE); // pow(1, ±inf): error 28, returned unchanged
    }
    y_inf_nan_tail(x, y)
}

/// RVA 0x39f9d: `y` infinite or NaN, `x` not NaN.
fn y_inf_nan_tail(x: f64, y: f64) -> f64 {
    let xb = x.to_bits();
    if y.to_bits() & FRAC != 0 {
        return y + y; // error 1006
    }
    if xb == 0xbff0_0000_0000_0000 {
        return f(ONE); // pow(-1, ±inf) = 1 (error 28)
    }
    let big = hw(x) & 0x7ff0 >= 0x3ff0;
    let yneg = y.to_bits() >> 63 != 0;
    if big != yneg { f(INF) } else { 0.0 }
}
